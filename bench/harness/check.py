"""Post-run checks on results.json, shared by run.py: negative savings and fixture refresh."""
from __future__ import annotations

import json
import shutil
from pathlib import Path

# Columns tried in order for "rtok-PR": the PR build without the reference line first.
PR_COLS = ("rtok-pr-noref", "rtok-pr", "rtok")


def pct(raw: int, tok: int) -> float:
    return (raw - tok) / raw * 100 if raw else 0.0


def negatives(rows: list[dict], competitor: str) -> list[str]:
    """One `WARN NEGATIVE` line per command (group total) and per scenario where the
    rtok-PR saving is lower than the competitor's. Never raises."""
    warn: list[str] = []
    groups: dict[str, dict[str, int]] = {}
    for r in rows:
        tools = r.get("tools", {})
        col = next((c for c in PR_COLS if tools.get(c, {}).get("supported")), None)
        comp = tools.get(competitor, {})
        if col is None or not comp.get("supported"):
            continue
        raw, mine, theirs = r["raw"], tools[col]["tokens"], comp["tokens"]
        g = groups.setdefault(r["group"], {"raw": 0, "mine": 0, "theirs": 0})
        g["raw"] += raw; g["mine"] += mine; g["theirs"] += theirs
        if mine > theirs:
            warn.append(f"WARN NEGATIVE: {r['group']} [{r['id']}] rtok {pct(raw, mine):.1f}% vs {competitor} {pct(raw, theirs):.1f}%")
    for name, g in groups.items():
        if g["mine"] > g["theirs"]:
            warn.insert(0, f"WARN NEGATIVE: {name} rtok {pct(g['raw'], g['mine']):.1f}% vs {competitor} {pct(g['raw'], g['theirs']):.1f}%")
    return warn


def report_negatives(out: Path, competitor: str) -> int:
    """Print the summary block and write negatives.txt; return the number of losses."""
    try:
        rows = json.loads((out / "results.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        print(f"WARN: cannot read {out / 'results.json'}: {e}")
        return 0
    warn = negatives(rows, competitor)
    (out / "negatives.txt").write_text("".join(w + "\n" for w in warn), encoding="utf-8")
    bar = "=" * 72
    print(bar)
    print(f"rtok-PR vs {competitor}: {len(warn)} negative line(s)")
    for w in warn:
        print(w)
    print(bar)
    return len(warn)


def _toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def refresh_fixtures(out: Path, dest: Path) -> int:
    """Copy samples/<case>/raw.txt into dest/<case>/ with case.toml. An existing
    `min_savings_pct` is kept, so a refresh never loosens or tightens a floor by itself."""
    rows = json.loads((out / "results.json").read_text(encoding="utf-8"))
    ver = json.loads((out / "versions.json").read_text(encoding="utf-8"))
    dest.mkdir(parents=True, exist_ok=True)
    for r in rows:
        src = out / "samples" / r["id"]
        cdir = dest / r["id"]
        old = cdir / "case.toml"
        floor = 0.0
        if old.is_file():
            for line in old.read_text(encoding="utf-8").splitlines():
                if line.startswith("min_savings_pct"):
                    floor = float(line.split("=", 1)[1])
        cdir.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src / "raw.txt", cdir / "raw.txt")
        argv = ", ".join(_toml_str(a) for a in r["argv"])
        (cdir / "case.toml").write_bytes((
            "# Generated by bench/harness/run.py --refresh-fixtures (rtok#1071).\n"
            f"group = {_toml_str(r['group'])}\n"
            f"argv = [{argv}]\n"
            f"fixture_commit = {_toml_str(ver.get('fixture_sha', ''))}\n"
            "# raw.txt is stderr followed by stdout, as `rtok run` sees them.\n"
            f"exit = {int(r.get('exit', 0))}\n"
            f"min_savings_pct = {floor}\n").encode("utf-8"))
    print(f"fixtures: {len(rows)} case(s) -> {dest}")
    return len(rows)
